import fs from "node:fs";
import { PNG } from "pngjs";

// Usage: node scripts/extract-sprites.mjs --probe <png>
//        node scripts/extract-sprites.mjs --preview <png> <scale> <ox> <oy> <x0> <y0> <x1> <y1> [cx0 cy0 cx1 cy1 keep]
//        node scripts/extract-sprites.mjs            (writes src/lib/sprites.generated.ts)

// Exact colours sampled from the claude-buddy snapshots. Keep in sync with src/lib/sprites.ts.
const PALETTE = {
  o: "#3d2236", p: "#ffd9b8", s: "#f0a487", h: "#fff3e4", g: "#62c46d", d: "#2f8f4e",
  b: "#ff8fa3", r: "#ff4d5e", w: "#ffffff", u: "#6ec6ff", y: "#ffd23f", t: "#3fd0c0",
  n: "#b8794a", m: "#b03a52", k: "#ff7eb6", c: "#fff6dc",
};

// Per-mood crop in source pixels, found with --preview. The art pixel is 12 source px
// and the grid sits at x = 4, y = 8 (mod 12) in every crisp frame, so box x0/y0 are
// chosen on-grid and ox/oy stay 0. done uses age 90: ages 0 and 170 are captured
// mid-animation and their edges are smeared off-grid.
const BUBBLE = [0, 0, 580, 488];     // everything above the sprout: bubble edge + tail
const TAIL = [0, 0, 400, 440];       // bubble tail only, left of the sign
const JOBS = {
  done:    { file: "scripts/snapshots/done-90.png",  scale: 12, ox: 0, oy: 0, box: [172, 440, 580, 800], clips: [{ rect: BUBBLE, keep: "y" }] },
  calm:    { file: "scripts/snapshots/wait-0.png",   scale: 12, ox: 0, oy: 0, box: [172, 404, 580, 800], clips: [{ rect: BUBBLE, keep: "" }] },
  annoyed: { file: "scripts/snapshots/wait-90.png",  scale: 12, ox: 0, oy: 0, box: [172, 404, 580, 800], clips: [{ rect: TAIL, keep: "" }] },
  angry:   { file: "scripts/snapshots/wait-170.png", scale: 12, ox: 0, oy: 0, box: [172, 404, 580, 800], clips: [{ rect: TAIL, keep: "" }] },
};

const hex = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const PAL = Object.entries(PALETTE).map(([k, v]) => [k, hex(v)]);

function load(file) { return PNG.sync.read(fs.readFileSync(file)); }
function px(png, x, y) {
  const i = (png.width * y + x) * 4;
  return [png.data[i], png.data[i + 1], png.data[i + 2], png.data[i + 3]];
}
function nearest(rgb) {
  let best = null, bestD = Infinity;
  for (const [k, c] of PAL) {
    const d = (c[0]-rgb[0])**2 + (c[1]-rgb[1])**2 + (c[2]-rgb[2])**2;
    if (d < bestD) { bestD = d; best = k; }
  }
  return { key: best, dist: Math.sqrt(bestD) };
}

// clips: [{ rect: [x0, y0, x1, y1], keep }] blanks every cell whose centre falls in rect
// (source pixels) unless its key is in keep. Used to drop the speech bubble's bottom
// edge and tail while keeping sparkles that overlap it.
function extract({ file, scale, ox, oy, box, clips = [] }) {
  const png = load(file);
  const [x0, y0, x1, y1] = box;
  const rows = [];
  for (let y = y0 + oy; y + scale <= y1; y += scale) {
    let row = "";
    for (let x = x0 + ox; x + scale <= x1; x += scale) {
      const c = px(png, x + (scale >> 1), y + (scale >> 1));
      const { key, dist } = nearest(c);
      const cx = x + (scale >> 1), cy = y + (scale >> 1);
      const clipped = clips.some(({ rect: [a, b, c, d], keep }) =>
        cx >= a && cx < c && cy >= b && cy < d && !keep.includes(key));
      row += dist < 40 && !clipped ? key : "."; // far from every palette colour = bg or shadow
    }
    rows.push(row);
  }
  // Trim empty leading/trailing rows (interior gaps are kept) and shared empty columns.
  const filled = rows.map((r) => /[^.]/.test(r));
  const keepRows = rows.slice(filled.indexOf(true), filled.lastIndexOf(true) + 1);
  const width = Math.max(...keepRows.map((r) => r.length));
  let minC = width, maxC = 0;
  for (const r of keepRows) for (let i = 0; i < r.length; i++) if (r[i] !== ".") { minC = Math.min(minC, i); maxC = Math.max(maxC, i); }
  const trimmed = keepRows.map((r) => r.slice(minC, maxC + 1));
  return { width: maxC - minC + 1, height: trimmed.length, rows: trimmed };
}

const [, , flag, ...args] = process.argv;

if (flag === "--probe") {
  // Print the most common horizontal run lengths: the art-pixel size is their gcd-ish mode.
  const png = load(args[0]);
  const counts = new Map();
  for (let y = 0; y < png.height; y += 5) {
    let x = 0;
    while (x < png.width) {
      const c = px(png, x, y).join(); let n = 1;
      while (x + n < png.width && px(png, x + n, y).join() === c) n++;
      counts.set(n, (counts.get(n) ?? 0) + 1); x += n;
    }
  }
  console.log([...counts].sort((a, b) => b[1] - a[1]).slice(0, 8));
} else if (flag === "--preview") {
  const [file, scale, ox, oy, a, b, c, d, ...cl] = args;
  const clips = cl.length ? [{ rect: cl.slice(0, 4).map(Number), keep: cl[4] ?? "" }] : [];
  const f = extract({ file, scale: +scale, ox: +ox, oy: +oy, box: [+a, +b, +c, +d], clips });
  console.log(`${f.width}x${f.height}`);
  console.log(f.rows.join("\n"));
} else {
  const out = {};
  for (const [mood, job] of Object.entries(JOBS)) out[mood] = extract(job);
  const body = `// Generated by scripts/extract-sprites.mjs from real claude-buddy snapshots. Do not edit.\nimport type { SpriteFrame } from "./sprites";\nimport type { MoodId } from "./moods";\n\nexport const SPRITES: Record<MoodId, SpriteFrame> = ${JSON.stringify(out, null, 2)};\n`;
  fs.writeFileSync("src/lib/sprites.generated.ts", body);
  console.log("wrote src/lib/sprites.generated.ts");
}
